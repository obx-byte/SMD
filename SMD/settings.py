# The station serves the inspection UI without any login, so its host allow-list
# is the main network boundary.  Only the configured station host (plus local
# development hosts) may reach it.  If the station must be reachable from the
# shop-floor LAN, add the station address here and put a reverse proxy / access
# control in front of it — do not open every route anonymously.
