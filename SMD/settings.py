# Vision Inspection — station identity
#
# This deployment is a **dedicated factory inspection station with no login**:
# operators scan parts and run inspections without a user account, so there is
# no authenticated operator to record.  Audit traceability is therefore carried
# by the *station identifier* configured here — never by a fabricated user
# identity.  Inspections saved from the station record this value as their
# operator label.
# ---------------------------------------------------------------------------

# Identifier of the physical station (shown in the UI and stored on records).
VISION_INSPECTION_STATION_ID = "STATION-01"

# Listen address for the station when run behind a WSGI server.  Loopback by
# default: the no-login routes must only be reachable from the station itself.
